def merge_runs(runs):
    merged = []
    for run in runs:
        if not run["text"]:
            continue
        if merged and merged[-1]["bold"] == run["bold"]:
            merged[-1]["text"] += run["text"]
        else:
            merged.append(dict(run))
    return merged


for day, (verse, reference) in KO_SCRIPTURES.items():
    path = KO_DIR / f"day-{day:02d}.json"
    payload = json.loads(path.read_text())
    payload["scripture"] = [
        {"runs": [{"text": verse, "bold": True}]},
        {"runs": [{"text": reference, "bold": True}]},
    ]
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")

# Spanish text already follows its source translation.  Fold standalone spaces
# into the preceding run so presentation metadata never creates a false-only
# run without changing the actual verse text or emphasis.
for path in ES_DIR.glob("day-*.json"):
    payload = json.loads(path.read_text())
    for block in payload["scripture"]:
        runs = []
        for run in block["runs"]:
            if run["text"].isspace() and runs:
                runs[-1]["text"] += run["text"]
            else:
                runs.append(dict(run))
        block["runs"] = merge_runs(runs)
    # Vision read an opening quotation mark as "66" and an inverted
    # exclamation mark as "i" in these rendered Scripture excerpts.
    for block in payload["scripture"]:
        for run in block["runs"]:
            run["text"] = run["text"].replace("66 ...", "“…").replace("66 ...una", "“…una").replace("iLa cuerda", "¡La cuerda")
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
